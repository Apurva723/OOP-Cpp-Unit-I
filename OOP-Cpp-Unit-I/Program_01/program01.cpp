#include <iostream>              // Header file for input and output operations
using namespace std;             // Allows us to use cout and endl without std::

int main() {
    int roll = 101;              // Declares an integer variable to store roll number
    char grade = 'A';            // Declares a character variable to store grade
    float fee = 12500.50;        // Declares a float variable to store fee amount

    cout << "Roll No: " << roll << endl;    // Displays the roll number
    cout << "Grade: " << grade << endl;     // Displays the grade
    cout << "Fee: " << fee << endl;         // Displays the fee amount

    return 0;                    // Indicates successful program execution
}